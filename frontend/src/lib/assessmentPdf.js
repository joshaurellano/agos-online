import { SECTIONS, FORM_TITLE, FORM_SOURCE } from './needsAssessment';

// Builds the assessment PDF from a payload made by formToRow(). The PDF
// libraries are loaded on first export so they stay out of the main bundle.

const INK = [20, 40, 63];
const HEAD_BG = [226, 236, 248];
const LINE = [160, 180, 205];

const dateLong = (key) => {
  if (!key) return '';
  const [y, m, d] = key.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1, d)).toLocaleDateString('en-PH', {
    year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC',
  });
};

const timeShort = (t) => {
  if (!t) return '';
  const [h, m] = t.split(':').map(Number);
  const hour = ((h + 11) % 12) + 1;
  return `${hour}:${String(m).padStart(2, '0')} ${h >= 12 ? 'PM' : 'AM'}`;
};

function answerText(field, value) {
  if (field.type === 'yesno') {
    const yes = value?.v === 'yes';
    const no = value?.v === 'no';
    let text = `[${yes ? 'x' : ' '}] Yes     [${no ? 'x' : ' '}] No`;
    if (value?.note) text += `\n${field.askLabel ?? 'Specify'}: ${value.note}`;
    return text;
  }
  if (field.type === 'count') return value == null || value === '' ? '-' : Number(value).toLocaleString('en-PH');
  if (field.type === 'date') return dateLong(value) || '-';
  if (field.type === 'time') return timeShort(value) || '-';
  return value ? String(value) : '-';
}

export async function buildAssessmentPdf(row) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
  ]);

  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const margin = 48;
  const common = {
    margin: { left: margin, right: margin, bottom: 54 },
    styles: { font: 'helvetica', fontSize: 10, textColor: INK, lineColor: LINE, lineWidth: 0.5, cellPadding: 6, valign: 'top' },
    headStyles: { fillColor: HEAD_BG, textColor: INK, fontStyle: 'bold' },
    theme: 'grid',
  };

  // ── Title ────────────────────────────────────────────────────────────
  doc.setFont('helvetica', 'bold').setFontSize(15).setTextColor(...INK);
  doc.text(FORM_TITLE.toUpperCase(), pageW / 2, 54, { align: 'center' });
  doc.setFont('helvetica', 'normal').setFontSize(9).setTextColor(90, 110, 135);
  doc.text(FORM_SOURCE, pageW / 2, 70, { align: 'center' });
  if (row.status === 'draft') {
    doc.setFont('helvetica', 'bold').setTextColor(180, 90, 0);
    doc.text('DRAFT', pageW - margin, 54, { align: 'right' });
  }

  // ── Header block ─────────────────────────────────────────────────────
  const team = row.team_members?.length
    ? row.team_members.map((m, i) => `${i + 1}. ${m}`).join('\n')
    : '-';
  autoTable(doc, {
    ...common,
    startY: 86,
    body: [
      ['Barangay', row.barangay || '-'],
      ['Date of assessment', dateLong(row.assessed_on) || '-'],
      ['Time of assessment', timeShort(row.assessed_time) || '-'],
      ['Team members', team],
    ],
    columnStyles: { 0: { cellWidth: 130, fontStyle: 'bold', fillColor: HEAD_BG }, 1: { cellWidth: 'auto' } },
  });

  // ── Sections ─────────────────────────────────────────────────────────
  SECTIONS.forEach((section) => {
    const body = section.fields.map((f) => [f.label, answerText(f, row.data?.[f.key])]);
    autoTable(doc, {
      ...common,
      startY: doc.lastAutoTable.finalY + 14,
      head: [[{ content: section.title.toUpperCase(), colSpan: 2 }]],
      body,
      columnStyles: { 0: { cellWidth: 250 }, 1: { cellWidth: 'auto' } },
      // Keep a section heading with at least its first row.
      rowPageBreak: 'avoid',
    });
  });

  // ── Signature block ──────────────────────────────────────────────────
  autoTable(doc, {
    ...common,
    startY: doc.lastAutoTable.finalY + 14,
    head: [[{ content: 'PREPARED BY', colSpan: 2 }]],
    body: [
      ['Name', row.prepared_by_name || ''],
      ['Position', row.prepared_by_position || ''],
      ['Signature', ''],
      ['Date', dateLong(row.prepared_on) || ''],
    ],
    columnStyles: { 0: { cellWidth: 130, fontStyle: 'bold', fillColor: HEAD_BG } },
    bodyStyles: { minCellHeight: 24 },
    rowPageBreak: 'avoid',
  });

  // ── Footer on every page ─────────────────────────────────────────────
  const pages = doc.getNumberOfPages();
  const made = new Date().toLocaleDateString('en-PH', { year: 'numeric', month: 'short', day: 'numeric', timeZone: 'Asia/Manila' });
  for (let i = 1; i <= pages; i += 1) {
    doc.setPage(i);
    const h = doc.internal.pageSize.getHeight();
    doc.setFont('helvetica', 'normal').setFontSize(8).setTextColor(110, 125, 145);
    doc.text(`Generated by AGOS on ${made}`, margin, h - 28);
    doc.text(`Page ${i} of ${pages}`, pageW - margin, h - 28, { align: 'right' });
  }
  return doc;
}

export function assessmentFileName(row) {
  const place = (row.barangay || 'barangay').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return `needs-assessment-${place}-${row.assessed_on || 'draft'}.pdf`;
}

export async function downloadAssessmentPdf(row) {
  const doc = await buildAssessmentPdf(row);
  doc.save(assessmentFileName(row));
}
